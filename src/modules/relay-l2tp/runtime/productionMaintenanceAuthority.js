const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { createHash, randomBytes } = require('node:crypto');
const { isDeepStrictEqual: equal } = require('node:util');
const { PRODUCTION_TOPOLOGY_EXECUTION_CONTEXT: PROD } = require('../domain/topologyExecutionContext');
const POLICY = '/etc/celerity/prod-admission-entry.json';
const HELPER = '/usr/local/libexec/c3-prod-maintenance/authority_helper.py';
const PYTHON = '/usr/bin/python3.13';
const CODE = 'PROD_MAINTENANCE_UNKNOWN_RETAINED';
const LIMIT = 131072;
function refusal(code = CODE) { return Object.assign(new Error(code), { code }); }
function need(ok) { if (!ok) throw refusal(); }
function attachCleanup(primary, secondary) {
    try { Object.defineProperty(primary, 'cleanupErrors', { configurable: true,
        value: [...(primary.cleanupErrors || []), secondary] }); } catch { /* preserve even frozen primary objects */ }
}
function freeze(value) {
    if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }
    return value;
}
function exact(value, keys) { return value && !Array.isArray(value) && Object.keys(value).sort().join(',') === [...keys].sort().join(','); }
function privateRead(file, { privateFile = true } = {}) {
    need(typeof file === 'string' && path.isAbsolute(file) && path.normalize(file) === file);
    for (let current = file; ; current = path.dirname(current)) {
        const st = fs.lstatSync(current);
        need(st.uid === 0 && !(st.mode & 0o022) && !st.isSymbolicLink());
        if (current === '/') break;
    }
    const fd = fs.openSync(file, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
    try {
        const st = fs.fstatSync(fd), named = fs.lstatSync(file);
        need(st.isFile() && (!privateFile || !(st.mode & 0o077)) && st.size <= (privateFile ? LIMIT : 64 * 1024 * 1024)
            && st.dev === named.dev && st.ino === named.ino);
        return fs.readFileSync(fd);
    } finally { fs.closeSync(fd); }
}
function readAccepted() {
    const config = JSON.parse(privateRead(POLICY));
    need(exact(config, ['version', 'challenge', 'mongoUri', 'helperSha256', 'pythonSha256']) && config.version === 1
        && equal(config.challenge?.serverContext, PROD)
        && typeof config.mongoUri === 'string' && config.mongoUri.startsWith('mongodb://')
        && ['helperSha256', 'pythonSha256'].every(key => typeof config[key] === 'string' && /^[a-f0-9]{64}$/.test(config[key])));
    // Root-only independently accepted manifest, complete raw-record pins and
    // first-install missing plan are consumed verbatim; NEVER generated by scans.
    return freeze(config);
}
class FixedHelperChannel {
    constructor(child, timeoutMs = 2000) {
        this.child = child; this.timeoutMs = timeoutMs; this.pending = null;
        this.buffer = Buffer.alloc(0); this.lost = false; this.closing = false;
        this.exited = new Promise(resolve => child.once('close', (code, signal) => {
            this.exit = { code, signal }; if (!this.closing) this.fail(); resolve(this.exit);
        }));
        child.once('error', () => this.fail());
        child.stdout.on('data', chunk => {
            if (this.lost) return;
            this.buffer = Buffer.concat([this.buffer, chunk]);
            if (this.buffer.length > LIMIT) return this.fail();
            const index = this.buffer.indexOf(10);
            if (index < 0) return;
            try {
                need(index === this.buffer.length - 1 && this.pending);
                const reply = JSON.parse(this.buffer.subarray(0, index).toString('utf8'));
                const pending = this.pending;
                need(exact(reply, ['version', 'nonce', 'verb', 'state']) && reply.version === 1
                    && reply.nonce === pending.nonce && reply.verb === pending.verb
                    && reply.state === (pending.verb === 'close' ? 'closed-retained' : 'held-retained'));
                this.pending = null; this.buffer = Buffer.alloc(0); clearTimeout(pending.timer);
                pending.resolve();
            } catch { this.fail(); }
        });
        child.stdout.once('end', () => { if (!this.closing || this.pending) this.fail(); });
        child.stdout.once('error', () => this.fail());
        child.stdin.on('error', () => this.fail());
        child.stderr.on('data', () => this.fail());
        child.stderr.once('error', () => this.fail());
    }
    fail() {
        this.lost = true;
        if (this.pending) { clearTimeout(this.pending.timer); this.pending.reject(refusal()); this.pending = null; }
    }
    async request(verb, challenge) {
        need(!this.lost && !this.pending && !this.exit && this.buffer.length === 0);
        if (verb === 'close') this.closing = true;
        await new Promise((resolve, reject) => {
            const nonce = randomBytes(32).toString('hex');
            const timer = setTimeout(() => this.fail(), this.timeoutMs);
            this.pending = { nonce, verb, timer, resolve, reject };
            this.child.stdin.write(JSON.stringify({ version: 1, nonce, verb, challenge }) + '\n', error => { if (error) this.fail(); });
        });
        need(!this.lost);
    }
    async dispose(expectSuccess = false) {
        this.closing = true;
        const errors = [];
        try { this.child.stdin.end(); } catch (error) { errors.push(error); }
        // Only this process-owned broker is reaped. External guards are NEVER
        // signaled and their retained exclusion does not depend on this pipe.
        let timer;
        const bounded = async () => {
            const answer = await Promise.race([this.exited, new Promise(resolve => { timer = setTimeout(() => resolve(null), this.timeoutMs); })]);
            clearTimeout(timer); return answer;
        };
        let result = await bounded();
        for (const signal of ['SIGTERM', 'SIGKILL']) {
            if (result) break;
            try { this.child.kill(signal); } catch (error) { errors.push(error); }
            result = await bounded();
        }
        for (const stream of [this.child.stdin, this.child.stdout, this.child.stderr]) {
            try { stream.destroy(); } catch (error) { errors.push(error); }
        }
        if (!result || (expectSuccess && (result.code !== 0 || result.signal !== null || this.lost))) errors.push(refusal());
        if (errors.length) {
            const primary = errors.shift(); errors.forEach(error => attachCleanup(primary, error)); throw primary;
        }
    }
}
function compose({ challenge: input, child, timeoutMs = 2000 }) {
    const accepted = freeze(structuredClone(input));
    need(equal(accepted.serverContext, PROD));
    const channel = new FixedHelperChannel(child, timeoutMs);
    let attempted = false;
    return Object.freeze({
        async withHeldMaintenance(challenge, work) {
            if (attempted) throw refusal('PROD_MAINTENANCE_ALREADY_ATTEMPTED');
            attempted = true;
            let open = true, unknown = false, primary, result;
            const assertHeld = async supplied => {
                try {
                    need(open && !channel.lost && equal(supplied, accepted));
                    await channel.request('check', accepted);
                    need(open && !channel.lost);
                } catch (error) {
                    unknown = true; channel.fail(); throw error;
                }
            };
            const retainUnknown = async supplied => {
                unknown = true;
                need(open && equal(supplied, accepted));
                await channel.request('retain', accepted);
            };
            try {
                need(equal(challenge, accepted) && typeof work === 'function');
                await assertHeld(challenge);
                result = await work(Object.freeze({ assertHeld, retainUnknown }));
                await assertHeld(challenge);
                need(!unknown);
                await channel.request('close', accepted);
            } catch (error) {
                primary = error;
                try { await retainUnknown(challenge); } catch { /* no release/retry exists */ }
            } finally {
                open = false;
                try { await channel.dispose(!primary); }
                catch (error) { if (!primary) primary = error; else attachCleanup(primary, error); }
            }
            if (primary) throw primary;
            return result;
        },
    });
}
function createProductionMaintenanceAuthority(accepted) {
    // Not an injection surface: root file is re-read; argument must be exactly
    // its independently accepted contents (private URI never leaves this module).
    const config = readAccepted();
    need(equal(config.challenge, accepted));
    need(createHash('sha256').update(privateRead(HELPER)).digest('hex') === config.helperSha256
        && createHash('sha256').update(privateRead(PYTHON, { privateFile: false })).digest('hex') === config.pythonSha256);
    let attempted = false;
    return Object.freeze({ async withHeldMaintenance(challenge, work) {
        if (attempted) throw refusal('PROD_MAINTENANCE_ALREADY_ATTEMPTED');
        attempted = true;
        need(equal(challenge, config.challenge) && typeof work === 'function');
        const child = spawn(PYTHON, ['-I', HELPER], { env: { LANG: 'C', PATH: '/usr/bin:/bin' }, stdio: ['pipe', 'pipe', 'pipe'] });
        return compose({ challenge: config.challenge, child }).withHeldMaintenance(challenge, work);
    } });
}
