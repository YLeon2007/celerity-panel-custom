'use strict';

// Deliberately executable RED acceptance cases: classic has no trusted applied
// descriptor reader. A real save-only pending peer and a previously dispatched
// legacy pending row cannot be distinguished by the persisted classic fields.
// Do not "fix" these by applying the TEST status filter to PROD.
const test = require('node:test');
const assert = require('node:assert/strict');
const { fixture, withEnv, node, link, MAIN, BRIDGE } = require('./cascadeLegacyWriterFixture');

function inventory(kind, status = 'pending') {
    const nodes = [node(1), node(2, 'bridge'), node(3), node(4, 'bridge')];
    const hop = kind === 'forward-hop';
    const fields = { mode: kind === 'reverse' ? 'reverse' : 'forward', status };
    const live = link(20, hop ? nodes[2] : nodes[0], hop ? nodes[0] : nodes[1], fields);
    const saved = link(21, hop ? nodes[3] : nodes[0], hop ? nodes[0] : nodes[3], fields);
    const inactive = link(22, hop ? nodes[1] : nodes[0], hop ? nodes[0] : nodes[2], { ...fields, active: false });
    return { nodes, live, saved, inactive };
}
async function rewrite(f, writer) {
    assert.equal(await (writer === 'sync' ? f.sync.updateXrayNodeConfig(f.nodes[0]) : f.cascade._deployPortalConfig(f.nodes[0])), true);
    return JSON.parse(f.files.get(f.key(f.nodes[0]._id, MAIN)));
}
function carries(config, descriptor) {
    return descriptor.mode === 'forward'
        ? JSON.stringify(config).includes(descriptor.tunnelUuid)
        : config.inbounds.some(inbound => inbound.port === descriptor.tunnelPort);
}
for (const writer of ['sync', 'cascade']) {
    for (const kind of ['reverse', 'forward-outbound', 'forward-hop']) {
        test(`${writer}/${kind}: compatibility preserves legacy active pending, offline, error and missing-status artifacts`, async () => withEnv({}, async () => {
            for (const status of ['pending', 'offline', 'error', undefined]) {
                const data = inventory(kind, status);
                if (status === undefined) for (const descriptor of [data.live, data.saved, data.inactive]) delete descriptor.status;
                // Historical active metadata is not a trusted native proof, but
                // neither is it authority to delete an already working artifact.
                const f = fixture({ nodes: data.nodes, links: [data.live, data.inactive] });
                const config = await rewrite(f, writer);
                assert.equal(carries(config, data.live), true, `${status} legacy artifact must survive`);
                assert.equal(carries(config, data.inactive), false);
                assert.ok(config.inbounds.some(inbound => inbound.settings?.clients?.some(client => client.id === f.users[0].xrayUuid)));
                assert.equal(f.locks.size, 0);
            }
        }));

        test(`UNRESOLVED ${writer}/${kind}: save-only pending neighbor must not be activated by a full classic rewrite`, async () => withEnv({}, async () => {
            const data = inventory(kind);
            const f = fixture({ nodes: data.nodes, links: [data.live, data.saved, data.inactive] });
            // Installed baseline is explicitly simulated, generated by the real
            // product generators. There is no new applied store/field or owner.
            const before = JSON.parse(f.generator.generateXrayConfigWithApi(data.nodes[0], f.users));
            const populated = { ...data.live, bridgeNode: data.nodes.find(node => node._id === data.live.bridgeNode) };
            if (kind === 'reverse') f.generator.applyReversePortal(before, [populated], ['clients']);
            else if (kind === 'forward-outbound') f.generator.applyForwardChain(before, [populated], ['clients']);
            else f.generator.applyForwardHopInbound(before, [populated]);
            f.files.set(f.key(data.nodes[0]._id, MAIN), JSON.stringify(before));
            f.files.set(f.key(data.nodes[0]._id, BRIDGE), 'untouched role profile');
            const peersBefore = structuredClone(f.links);
            const after = await rewrite(f, writer);
            assert.equal(carries(after, data.live), true, 'preserve working legacy pending artifact');
            assert.equal(carries(after, data.inactive), false, 'inactive neighbor stays absent');
            assert.deepEqual(f.links, peersBefore);
            assert.equal(f.files.get(f.key(data.nodes[0]._id, BRIDGE)), 'untouched role profile');
            assert.equal(carries(after, data.saved), false,
                'INV-05: genuine save-only pending peer was silently included; classic has no trusted baseline/provenance contract');
        }));
    }
}
