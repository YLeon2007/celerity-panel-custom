    def test_unexpected_origin_source_or_exec_refused(self):
        for key, value in (('FragmentPath', '/run/systemd/generator/xl2tpd.service'),
                           ('SourcePath', '/usr/local/etc/init.d/xl2tpd'),
                           ('ExecStop', exec_property(INIT, INIT + ' stop extra')),
                           ('Job', '17'), ('DropInPaths', '/gone/foreign.conf')):
            with self.subTest(key=key):
                self.info_changes['xl2tpd.service'] = {key: value}
                self.refused('UNIT_STATE')

    def test_manager_lookup_and_missing_or_duplicate_properties_fail_closed(self):
        self.manager_paths += ' /etc/foreign-unit-dir'
        self.refused('UNIT_STATE')
        self.manager_paths = '/etc/systemd/system /usr/lib/systemd/system /run/systemd/generator.late'
        for output in ('LoadState=not-found\n', 'LoadState=loaded\nLoadState=not-found\n'):
            with self.subTest(output=output):
                self.result_override = (output, 1, '')
