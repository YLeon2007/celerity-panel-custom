    def test_generator_body_and_metadata_refused(self):
        self.put(GENERATED, ENABLED_WRAPPER + b'# imitation\n')
        self.refused('UNIT_FILES')
        self.put(GENERATED, ENABLED_WRAPPER, 0o664)
        self.refused('UNIT_FILES')

    def test_modeled_systemd_257_8_with_exact_provenance_and_output(self):
        self.seed_generator()
        generator = self.observe()['inputs']['generator']
        self.assertEqual(generator[:2], [VENDOR_GENERATOR, hashlib.sha256(MODELED_GENERATOR).hexdigest()])
        for binary, verb in (('dpkg-query', '-S'), ('dpkg-divert', '--truename')):
            self.assertIn((f'/usr/bin/{binary}', verb, VENDOR_GENERATOR), self.calls)
        self.assertEqual(self.prepare(), 'created')
        self.assertEqual(self.observe()['inputs']['generator'], generator)

    def test_direct_binds_only_the_stock_effective_generator(self):
        generator = self.entry['generator_input']
        local = '/etc/systemd/system-generators/systemd-sysv-generator'
        self.seed_generator()
        with patch.dict(generator.__globals__, ROOT_OWNER=(os.getuid(), os.getgid())):
            with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_STATE'):
                generator(self.root, self.run_command, missing=True, strict=True)
            self.put(local, MODELED_GENERATOR, 0o755)
            with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_STATE'):
                generator(self.root, self.run_command, missing=False, strict=True)
            self.path(local).unlink()
            self.path(local).symlink_to('/dev/null')
            self.assertEqual(generator(self.root, self.run_command, missing=True, strict=True)[:2], [local, 'masked'])
        with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_STATE'):
            self.observe()
        self.remove_wrapper_files()
        self.wrapper = None
        self.assertEqual(self.prepare(), 'stock-not-found')

    def test_generator_md5_must_be_single_exact_entry_and_match(self):
        self.seed_generator()
        sums = self.path(GENERATOR_SUMS).read_bytes()
        for row in (b'', sums + sums, sums.replace(b'usr/lib/', b'lib/', 1),
                    sums.replace(b'  usr/', b'  /usr/', 1), b'0' * 32 + sums[32:]):
            with self.subTest(row=row):
                self.put(GENERATOR_SUMS, row)
                with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_FILES'):
                    self.observe()
                self.refused('UNIT_FILES')

    def test_generator_owner_and_truename_replies_are_exact(self):
        self.seed_generator()
        path = VENDOR_GENERATOR
        query = ('/usr/bin/dpkg-query', '-S', path)
        divert = ('/usr/bin/dpkg-divert', '--truename', path)
        for argv, reply in ((query, (f'foreign: {path}\n',)),
                            (query, (f'systemd:amd64: {path}\n',)),
                            (query, (f'systemd: {path}\nforeign: {path}\n',)),
                            (query, (f'systemd: {path}\r\n',)),
                            (query, (f'systemd: {path}\n', 1, '')),
                            (query, (f'systemd: {path}\n', 0, 'warning\n')),
                            (divert, (f'{path}.distrib\n',)),
                            (divert, (f'{path}\n\n',))):
            with self.subTest(argv=argv, reply=reply):
                self.generator_replies = {argv: reply}
                with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_FILES'):
                    self.observe()
                self.refused('UNIT_FILES')

    def test_standalone_capture_leaves_dpkg_reply_newlines_exact(self):
        argv = ('/usr/bin/dpkg-query', '-S', VENDOR_GENERATOR)
        stdout = f'systemd: {VENDOR_GENERATOR}\r\n'
        result = subprocess.CompletedProcess(argv, 0, stdout.encode(), b'')
        with patch.object(subprocess, 'run', return_value=result) as run:
            self.assertEqual(self.entry['command'](*argv).stdout, stdout)
        run.assert_called_once_with(argv, stdin=subprocess.DEVNULL, capture_output=True, timeout=30,
                                    env={'PATH': '/usr/sbin:/usr/bin:/sbin:/bin', 'LC_ALL': 'C'})

    def test_proven_generator_does_not_authorize_changed_wrapper_output(self):
        self.seed_generator()
        self.put(GENERATED, ENABLED_WRAPPER + b'# changed output\n')
        with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_FILES'):
            self.observe()
        self.refused('UNIT_FILES')

    def test_generator_and_manifest_require_trusted_regular_files(self):
        self.seed_generator()
        for path, bad_mode, good_mode in ((VENDOR_GENERATOR, 0o710, 0o755), (GENERATOR_SUMS, 0o664, 0o644)):
            with self.subTest(path=path):
                disk = self.path(path)
                disk.chmod(bad_mode)
                self.refused('UNIT_FILES')
                disk.chmod(good_mode)
                saved = disk.with_suffix('.saved')
                disk.rename(saved)
                disk.symlink_to(saved.name)
                self.refused('UNIT_FILES')
                disk.unlink()
                os.link(saved, disk)
                self.refused('UNIT_FILES')
                saved.unlink()
        self.path(GENERATOR_SUMS).parent.chmod(0o777)
        self.refused('UNIT_FILES')

    def test_generator_and_manifest_must_stay_bound_to_held_files(self):
        self.seed_generator()
        for path, mode in ((VENDOR_GENERATOR, 0o755), (GENERATOR_SUMS, 0o644)):
            with self.subTest(path=path):
                def replace_on_query(*argv):
                    result = self.run_command(*argv)
                    if argv == ('/usr/bin/dpkg-query', '-S', VENDOR_GENERATOR):
                        disk = self.path(path)
                        # Byte-identical substitution must not borrow an old FD's proof.
                        data = disk.read_bytes()
                        disk.rename(disk.with_suffix('.old'))
                        self.put(path, data, mode)
                    return result

                with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_FILES'):
                    self.observe(replace_on_query)

    def test_generator_and_manifest_reads_are_bounded(self):
        self.seed_generator()
        for path, mode in ((VENDOR_GENERATOR, 0o755), (GENERATOR_SUMS, 0o644)):
            with self.subTest(path=path):
                original = self.path(path).read_bytes()
                with self.path(path).open('r+b') as handle:
                    handle.truncate(1024 * 1024 + 1)
                self.refused('UNIT_FILES')
                self.put(path, original, mode)

    def test_package_facts_are_separately_required(self):
        original = self.package
        self.package = original.replace('1.3.18-1+b1', '1.3.18-1+b2')
        self.refused('PACKAGE_FACTS')
        self.package = original
        self.owners[DEFAULTS] = 'another-package'
        self.refused('PACKAGE_FACTS')

    def test_helper_does_not_overwrite_a_late_file(self):
        self.on_idle_queue = lambda: self.put(NATIVE, b'other writer\n')
        with self.assertRaisesRegex(self.entry['Refusal'], 'CREATE_FAILED'):
            self.prepare()
        self.assertEqual(self.path(NATIVE).read_bytes(), b'other writer\n')
        self.assertFalse(any('daemon-reload' in a for a in self.calls))

    def test_reload_failure_is_not_reported_as_success(self):
        self.allow_reload = False
        with self.assertRaisesRegex(self.entry['Refusal'], 'RELOAD_FAILED'):
            self.prepare()
        self.assertEqual(self.path(NATIVE).read_bytes(), NATIVE_BYTES)

    def test_reload_success_does_not_substitute_for_exact_readback(self):
        def run(*argv):
            result = self.run_command(*argv)
            if 'daemon-reload' in argv:
                self.info_changes['xl2tpd.service'] = {'NeedDaemonReload': 'yes'}
            return result

        prepare = self.entry['prepare']
        with patch.dict(prepare.__globals__, ROOT_OWNER=(os.getuid(), os.getgid())):
            with self.assertRaisesRegex(self.entry['Refusal'], 'UNIT_STATE'):
                prepare(self.root, run)
        self.assertEqual(self.path(NATIVE).read_bytes(), NATIVE_BYTES)
        self.assertEqual(sum('daemon-reload' in a for a in self.calls), 1)


